/*
一个大于1的正整数若等于全部因子的和，则称此数为完全数。例如：6 有因子 1，2，3。同时 1+2+3=6所以6 是完全数。
输入格式:
一个正整数n（<10000）
输出格式:
小于等于n的完全数的个数。
输入样例:
在这里给出一组输入。例如：
10
输出样例:
在这里给出相应的输出。例如：
1
*/
#include <stdio.h>
int main(){    
int n;    
scanf("%d",&n);    
int count = 0;
    
for(int i = 2;i<=n;i++){        
int sum = 0;
        
for(int k = 1;k<=i/2;k++){            
if(i%k==0){sum += k;}        
    }    //因为因子不可能大于原数一半，故条件是i/2
	    
if(sum == i)        //每一个因子都会循环，你错认为要一次性输出两个因子
count++;    
         }
		     
printf("%d\n",count);    
return 0;
}