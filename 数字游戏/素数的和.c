/*素数也成为质数，指的是大于1的整数中，只能被1和这个数本身整除的数。
从键盘输入一系列大于1的正整数，输入1时表示输入结束。
求输入的这些正整数中素数的和。

输入格式:
从键盘输入一系列大于1的正整数，输入1时表示输入结束。

输出格式:
输入的这些正整数中素数的和。

输入样例:
10 11 13 9 8 7 1
输出样例:
31
注意:
有可能在输入的所有整数中，一个素数也没有。*/
#include <stdio.h>
int main(){    
int n = 0;    
int sum = 0; 
   
while(n!=1){        
scanf("%d",&n);        
int isprime = 1;
        
for(int i = 2;i*i<=n;i++){            
    if(n%i==0){isprime = 0;break;}        
    }//经典找质数环节
	
	        
if(isprime&&n>1){            
sum = sum + n;        
}    //找完求和
}    
printf("%d\n",sum);    
return 0;
}