/*这是一个编程题模板。
输入第一行给出正偶数N（N小于等于50），
即全班学生的人数。此后N行，按照名次从高到低的顺序给出每个学生的性别（0代表女生，1代表男生）和姓名（不超过8个英文字母的非空字符串），
其间以1个空格分隔。这里保证本班男女比例是1:1，并且没有并列名次。要求：每行输出一组两个不同性别学生的姓名，其间以1个空格分隔。
名次高的学生在前，名次低的学生在后。小组的输出顺序按照前面学生的名次从高到低排列。
输入格式:
输入第一行给出正偶数N（N小于等于50），即全班学生的人数。
此后N行，按照名次从高到低的顺序给出每个学生的性别（0代表女生，1代表男生）和姓名（不超过8个英文字母的非空字符串），
其间以1个空格分隔。
输出格式:
每行输出一组两个不同性别学生的姓名，其间以1个空格分隔。
名次高的学生在前，名次低的学生在后。
小组的输出顺序按照前面学生的名次从高到低排列。

输入样例:
在这里给出一组输入。例如：

2
1 Tom
0 Alice
输出样例:
在这里给出相应的输出。例如：

Tom Alice
*/
#include <stdio.h>
int main(){    
int N;    
scanf("%d",&N);  
  
char name[55][10];    
int sex;
    
for(int i = 0;i<N;i++){        
scanf("%d %s",&sex,name[i]);    
}
    
int half = N / 2;    
for(int i = 0;i<half;i++){        
printf("%s %s\n",name[i],name[i+half]);    
}
    
return 0;
}
//把队伍从中间劈成两半，前半段第 i 个人，和后半段第 i 个人凑一组。 
//因为题目保证这样配出来的每对都是一男一女，所以连性别都不用看，光靠位置就能直接输出。